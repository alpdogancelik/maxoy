export function t(lang, key, vars = {}) {
  const target = TRANSLATIONS[lang] || TRANSLATIONS.tr;
  const parts = key.split(".");
  let value = target;
  for (const part of parts) {
    value = value?.[part];
  }
  if (typeof value !== "string") return key;
  return value.replace(/\{(\w+)\}/g, (_, v) => vars[v] ?? "");
}

