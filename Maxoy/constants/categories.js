export const SUBCATEGORIES_BY_MAIN = MAIN_CATEGORIES.reduce((acc, main) => {
  acc[main.code] = SUBCATEGORIES.filter((s) => s.main === main.code);
  return acc;
}, {});

export function getMainCodeFromSubcategory(code) {
  if (!code || typeof code !== "string") return "";
  return code.trim().charAt(0).toUpperCase();
}

export function getMainCategoryTitle(mainCode) {
  const found = MAIN_CATEGORIES.find((c) => c.code === mainCode);
  return found?.title || mainCode || "";
}

export function getSubcategoryTitle(code) {
  const found = SUBCATEGORIES.find((c) => c.code === code);
  return found?.title || code || "";
}

export function getMainCategoryTitleByLang(mainCode, lang = "tr") {
  const found = MAIN_CATEGORIES.find((c) => c.code === mainCode);
  if (!found) return mainCode || "";
  return lang === "en" ? found.titleEn || found.title : found.title;
}

export function getSubcategoryTitleByLang(code, lang = "tr") {
  const found = SUBCATEGORIES.find((c) => c.code === code);
  if (!found) return code || "";
  return lang === "en" ? found.titleEn || found.title : found.title;
}
